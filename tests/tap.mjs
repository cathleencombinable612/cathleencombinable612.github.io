import { chromium } from 'playwright'
const url = process.argv[2], out = '/workspace/screenshots/'
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] })
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true })
const errs = []; p.on('pageerror', e => errs.push(e.message))
await p.goto(url, { waitUntil: 'networkidle' })
await p.screenshot({ path: out + 'pulse-library-songs.png' })
await p.getByRole('button', { name: /Play song/ }).nth(5).tap()
await p.waitForTimeout(5000)
const bar = await p.locator('.sticky.top-16').innerText(); console.log('player:', bar.replace(/\n/g, ' | '))
await p.screenshot({ path: out + 'pulse-top-player-playing.png' })
await p.locator('.sticky.top-16 button.flex-1').tap(); await p.waitForTimeout(600)
await p.screenshot({ path: out + 'pulse-song-form.png' })
await p.getByRole('button', { name: 'Browse' }).tap(); await p.waitForTimeout(300)
await p.getByPlaceholder(/Search/).fill('7/8'); await p.waitForTimeout(200)
await p.getByPlaceholder(/Search/).fill('')
await p.locator('select.sel').nth(1).selectOption('7/8'); await p.waitForTimeout(300)
await p.screenshot({ path: out + 'pulse-browse-7-8.png' })
await p.getByRole('button', { name: /Add .* as a layer/ }).first().tap(); await p.waitForTimeout(200)
await p.getByRole('button', { name: 'Sound' }).tap(); await p.waitForTimeout(300)
await p.screenshot({ path: out + 'pulse-sound-fills.png' })
await p.getByRole('button', { name: 'Close player' }).tap(); await p.waitForTimeout(500)
const closed = await p.getByRole('dialog', { includeHidden: true }).getAttribute('aria-hidden'); console.log('sheet hidden after close:', closed)
await p.goto(url + '#/lens/freese'); await p.waitForTimeout(800)
await p.screenshot({ path: out + 'pulse-drummers-lens-freese.png', fullPage: false })
console.log('errors', errs)
await b.close()

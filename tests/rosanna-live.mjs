import { chromium } from 'playwright'
const URL = 'https://nmpy7knjd8-code.github.io/rhythm/'
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] }); const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
await p.goto(URL + '?v=' + Date.now() + '#/library', { waitUntil: 'networkidle' }); await p.waitForTimeout(500)
const titles = await p.locator('main article h2').allInnerTexts()
console.log('songs:', titles.length, '| offenders:', titles.filter(t => /reference|generic|Journey/i.test(t)).join(', ') || 'none')
await p.screenshot({ path: '/workspace/screenshots/v4-songs.png' })
const r = await p.evaluate(async () => { await window.__pulseLoadSong('rosanna', 0); const e = window.__pulseEngine; e.jumpSong(1); e.trace = []; await e.start(); await new Promise(r => setTimeout(r, 3200)); e.stop()
  return e.trace.filter(x => x.src === 'song' && x.voice === 'tick').map(x => x.t) })
const d = r.slice(1).map((t, i) => Math.round((t - r[i]) * 1000)); console.log('Rosanna hat intervals ms:', d.slice(0, 16).join(' '), '(expect long-short 2:1 = 244/122 at 82 BPM)')
await p.locator('[aria-label="Browse rhythms"]').click(); await p.waitForTimeout(500)
console.log('sheet header:', (await p.locator('[role=dialog] .touch-none').innerText()).replace(/\n/g, ' | '))
await p.screenshot({ path: '/workspace/screenshots/v4-rosanna-sheet.png' })
await p.goto(URL + '#/story', { waitUntil: 'networkidle' }); await p.waitForTimeout(400)
await p.getByText('Style studies').scrollIntoViewIfNeeded(); await p.screenshot({ path: '/workspace/screenshots/v4-story-studies.png' })
console.log('style studies listed:', await p.locator('section:has(h2:text("Style studies")) li').count())
await b.close()
